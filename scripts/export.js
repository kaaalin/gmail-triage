#!/usr/bin/env node
'use strict';
/**
 * Generates the reviewable exports (prompts/ and config/) from src/Code.gs, the single source of truth.
 *
 *   node scripts/export.js           write the files
 *   node scripts/export.js --check   fail (exit 1) if any committed file differs from what Code.gs produces
 *
 * Apps Script cannot read files from this repository at runtime, so the prompt and schema live inside
 * Code.gs. These exports exist so they can be reviewed, diffed and reused without reading 1,200 lines of code.
 */
const fs = require('fs');
const path = require('path');
const {ROOT, loadCode, zonedToEpochMs} = require('./lib/gas-sandbox');
const csv = require('./lib/csv');

function json(v) { return JSON.stringify(v, null, 2) + '\n'; }

function generate() {
  const code = loadCode();
  const g = code.get;
  const files = {};

  // ---- prompts ---------------------------------------------------------------
  files['prompts/system_prompt.txt'] = g('SYSTEM_PROMPT') + '\n';
  files['prompts/response_schema.json'] = json(g('TRIAGE_TOOL'));

  // The exact HTTP request body the script sends for one email (first practice email, placeholder model).
  const input = csv.parse(fs.readFileSync(path.join(ROOT, 'data', 'input', 'Practice_Mailbox_40.csv'), 'utf8'));
  const first = input[1];
  const msg = {
    id: first[0], receivedMs: zonedToEpochMs(first[1], code.timeZone),
    fromName: first[3], fromEmail: first[4], subject: first[5], body: first[6]
  };
  files['prompts/example_request.json'] = json(code.sandbox.buildRequest_(msg, {model: '<CLAUDE_MODEL>'}));

  // ---- configuration exports -------------------------------------------------
  const cfg = g('CFG');
  files['config/runtime-settings.json'] = json(cfg);
  files['config/taxonomy.json'] = json({
    output_columns: g('HEADERS'),
    state_sheet_columns: g('STATE_HEADERS'),
    categories: g('CATEGORIES'),
    owners: g('OWNERS'),
    urgencies: g('URGENCIES'),
    languages: g('LANGUAGES'),
    confidences: g('CONFIDENCES'),
    escalate_values: g('YES_NO')
  });
  const sig = g('SIGNATURE_TEAMS');
  files['config/signatures.json'] = json({
    airport_name: g('AIRPORT_NAME'),
    closing: g('CLOSING'),
    greeting_generic: g('GREETING_GENERIC'),
    greeting_ict: g('GREETING_ICT'),
    greeting_named_examples: {EN: g('GREETING_NAMED').EN('<Name>'), BG: g('GREETING_NAMED').BG('<Name>')},
    signature_teams_by_owner: sig
  });
  const spec = {
    category: 'Supplier invoices', urgency: 'U3', owner: 'Technical/Infrastructure',
    action: 'Verify the invoice and payment status with the payment approver.',
    confidence: 'High', escalate: 'Yes'
  };
  files['config/label-scheme.example.json'] = json({
    note: 'Six labels per Gmail message. Generated by labelNamesFor_() for the sample values below.',
    sample_values: spec,
    labels: code.sandbox.labelNamesFor_(spec),
    action_label_max_chars: g('ACTION_LABEL_MAX'),
    legacy_labels_removed_by_backfill: g('LEGACY_ACTION_LABELS')
  });
  const P = cfg.PROP;
  const props = {};
  props[P.KEY] = '<paste your Anthropic API key here; never commit a real key>';
  props[P.MODEL] = '<a model ID your key can use>';
  props[P.SHEET_ID] = '<ID from the spreadsheet URL>';
  props[P.ALLOW] = '<optional: comma-separated sender addresses or @domains; leave unset to process everyone>';
  files['config/script-properties.example.json'] = json({
    where: 'Apps Script editor -> Project Settings -> Script Properties. Do not store these in the repository.',
    required: [P.KEY, P.MODEL, P.SHEET_ID],
    optional: [P.ALLOW],
    managed_by_the_script: [P.START],
    example: props
  });
  return files;
}

function main() {
  const check = process.argv.includes('--check');
  const files = generate();
  const stale = [];
  Object.keys(files).sort().forEach(function (rel) {
    const abs = path.join(ROOT, rel);
    if (check) {
      const have = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : null;
      if (have !== files[rel]) stale.push(rel);
    } else {
      fs.mkdirSync(path.dirname(abs), {recursive: true});
      fs.writeFileSync(abs, files[rel], 'utf8');
      console.log('wrote ' + rel);
    }
  });
  if (check) {
    if (stale.length) {
      console.error('Exports are out of date with src/Code.gs. Run "npm run export" and commit:\n  ' + stale.join('\n  '));
      process.exit(1);
    }
    console.log('Exports match src/Code.gs (' + Object.keys(files).length + ' files).');
  }
}

if (require.main === module) main();
module.exports = {generate};
